"""Where the app keeps things, which server it talks to, and the field defaults.

Data lives in %LOCALAPPDATA%\\StateLife\\DeviceInstaller on Windows and in
~/Library/Application Support/StateLife/DeviceInstaller on macOS (bench tests).
The server is https://autoattn.slichealth.com; only ``--server`` changes it, for
tests.

resources/field_defaults.json is generated by the release build from GitHub
secrets and never committed. Without it the app is a test build: the secret-looking
defaults (Wi-Fi password, comm key, hotspot password) stay empty.

From a source checkout the tools run as ``python -m esptool`` with this Python.
esptool 5.1.0 needs Python 3.10 or newer, so a bench whose own Python is older (the
Mac's 3.9 has esptool 4.7) names another interpreter in SL_INSTALLER_TOOL_PYTHON,
or with the bench's ``--tool-python``. The frozen app always runs its own copy.
"""
from __future__ import annotations

import json
import os
import sys
from dataclasses import dataclass, fields, replace
from pathlib import Path
from typing import Dict, Optional

from . import __version__
from .core.api import FieldDefaults

DEFAULT_SERVER = "https://autoattn.slichealth.com"
DATA_DIR_ENV = "SL_INSTALLER_DATA_DIR"
TOOL_PYTHON_ENV = "SL_INSTALLER_TOOL_PYTHON"
SIGNING_KEY_NAME = "firmware-signing-key-1.pem"
STORAGE_IMAGE_NAME = "storage-empty.bin.gz"
FIELD_DEFAULTS_NAME = "field_defaults.json"


def resources_dir() -> Path:
    # Frozen (PyInstaller) builds keep package data next to the bundled modules,
    # so this resolves inside the install folder there as well.
    return Path(__file__).resolve().parent / "resources"


def default_data_dir() -> Path:
    override = os.environ.get(DATA_DIR_ENV)
    if override:
        return Path(override)
    if sys.platform == "win32":
        base = os.environ.get("LOCALAPPDATA") or str(Path.home() / "AppData" / "Local")
        return Path(base) / "StateLife" / "DeviceInstaller"
    if sys.platform == "darwin":
        return Path.home() / "Library" / "Application Support" / "StateLife" / "DeviceInstaller"
    base = os.environ.get("XDG_DATA_HOME") or str(Path.home() / ".local" / "share")
    return Path(base) / "StateLife" / "DeviceInstaller"


@dataclass(frozen=True)
class AppConfig:
    server_url: str
    data_dir: Path
    resources_dir: Path
    frozen: bool
    app_version: str
    # Source checkouts only: the Python that runs ``-m esptool|espefuse`` (None: this one).
    tool_python: Optional[str] = None

    @property
    def bundles_dir(self) -> Path:
        return self.data_dir / "bundles"

    @property
    def logs_dir(self) -> Path:
        return self.data_dir / "logs"

    @property
    def records_dir(self) -> Path:
        return self.data_dir / "records"

    @property
    def state_dir(self) -> Path:
        return self.data_dir / "state"

    @property
    def work_dir(self) -> Path:
        """Private scratch space; secrets live here only while a step needs them."""
        return self.data_dir / "work"

    @property
    def signing_key_path(self) -> Path:
        return self.resources_dir / SIGNING_KEY_NAME

    @property
    def storage_image_path(self) -> Path:
        return self.resources_dir / STORAGE_IMAGE_NAME

    @property
    def field_defaults_path(self) -> Path:
        return self.resources_dir / FIELD_DEFAULTS_NAME

    def ensure_dirs(self) -> None:
        for path in (self.bundles_dir, self.logs_dir, self.records_dir, self.state_dir,
                     self.work_dir):
            path.mkdir(parents=True, exist_ok=True)


def load_config(server_url: Optional[str] = None, data_dir: Optional[Path] = None,
                resources: Optional[Path] = None,
                tool_python: Optional[str] = None) -> AppConfig:
    url = (server_url or DEFAULT_SERVER).rstrip("/")
    if not url.startswith("https://") and not url.startswith("http://127.0.0.1") \
            and not url.startswith("http://localhost"):
        raise ValueError("the server must use https")
    frozen = bool(getattr(sys, "frozen", False))
    # The frozen app is its own esptool: nothing may point it at another program.
    python = None if frozen else (tool_python or os.environ.get(TOOL_PYTHON_ENV) or None)
    return AppConfig(server_url=url, data_dir=Path(data_dir) if data_dir else default_data_dir(),
                     resources_dir=Path(resources) if resources else resources_dir(),
                     frozen=frozen, app_version=__version__, tool_python=python)


_INT_FIELDS = {"zkt_port", "zkt_comm_key", "hik_port"}


def load_field_defaults(path: Path) -> FieldDefaults:
    """Release defaults from ``path``; the test-build defaults when it does not exist.

    Raises ValueError for a file that exists but is not valid, so a broken release
    is caught by the self-test instead of silently shipping empty secrets.
    """
    if not path.is_file():
        return FieldDefaults()
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        raise ValueError(f"{path.name} is not valid JSON") from error
    if not isinstance(data, dict):
        raise ValueError(f"{path.name} must hold an object")
    known = {item.name for item in fields(FieldDefaults)} - {"is_test_build"}
    values: Dict[str, object] = {}
    for key, value in data.items():
        if key not in known:
            raise ValueError(f"{path.name} has an unknown key {key!r}")
        if key in _INT_FIELDS:
            if type(value) is not int:
                raise ValueError(f"{path.name}: {key} must be a number")
        elif not isinstance(value, str):
            raise ValueError(f"{path.name}: {key} must be text")
        values[key] = value
    defaults = replace(FieldDefaults(), is_test_build=False, **values)
    if not (1 <= defaults.zkt_port <= 65535 and 1 <= defaults.hik_port <= 65535
            and 0 <= defaults.zkt_comm_key <= 0xFFFFFFFF):
        raise ValueError(f"{path.name}: a port or the comm key is out of range")
    return defaults
